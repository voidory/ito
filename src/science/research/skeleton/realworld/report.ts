/**
 * FEAT-005B — markdown report generation for the real-world benchmark and the
 * failure analysis. Pure string building over a {@link BenchmarkReport}.
 */

import { CARBON_SKELETON_CORPUS } from "../fixtures";
import type { AggregateMetrics } from "./metrics";
import type { BenchmarkReport, EvaluatedCase } from "./runBenchmark";

function pct(x: number): string {
  return (x * 100).toFixed(1) + "%";
}

function aggRow(label: string, a: AggregateMetrics): string {
  return (
    `| ${label} | ${a.count} | ${pct(a.exactRate)} | ${a.vertexF1.toFixed(3)} | ` +
    `${a.bondF1.toFixed(3)} | ${a.meanGraphEditDistance.toFixed(2)} | ` +
    `${pct(a.cycleRankAccuracy)} | ${pct(a.branchTopologyAccuracy)} |`
  );
}

const HEADER = "| | n | exact | vertex F1 | bond F1 | mean GED | μ acc | branch topo |";
const SEP = "|---|---|---|---|---|---|---|---|";

export function buildRealWorldReport(report: BenchmarkReport): string {
  const L: string[] = [];
  L.push("# FEAT-005B — Real-World Carbon-Skeleton Benchmark");
  L.push("");
  L.push(
    "Auto-generated by `report.test.ts` (run with `ITO_WRITE_REALWORLD_REPORT=1`). " +
      "Single source of truth: `realworld/corpus.ts` → `manifest.json` → Pillow " +
      "renderer (`scripts/gen-realworld-corpus.py`) → `png/*.png` + `variants.json`.",
  );
  L.push("");
  L.push("## What this benchmark is — and is not");
  L.push("");
  L.push(
    "- **Separate category.** These are REAL named organic structures reduced to " +
      "their carbon skeletons and scored on their own. Their numbers are **never " +
      "combined** with the synthetic SVG fixture benchmark (`../BENCHMARK.md`).",
  );
  L.push(
    "- **Rendered, not scanned.** Each image is a genuine anti-aliased PNG produced " +
      "by a raster engine (Pillow, 4× supersampling) with real-diagram artefacts: " +
      "anti-aliasing, varied line weights, element/group labels placed next to or " +
      "touching bonds, non-120° angles, a range of resolutions, and (on the " +
      "held-out set) rotation, skew, lossy compression, Gaussian / salt-and-pepper " +
      "noise, reduced resolution and reduced contrast.",
  );
  L.push(
    "- **Honest limitation.** Rendered structures are NOT photographs of scanned " +
      "textbook pages or hand-drawn diagrams. They exercise the *actual* PNG-decode " +
      "path and the real-diagram artefacts the 1px SVG fixtures lack, but " +
      "photographed-page evaluation remains the final validation step before " +
      "automatic recognition is trusted in the Identify workflow.",
  );
  L.push("");
  L.push(
    "- **Dev/eval split honoured.** The corpus is partitioned deterministically " +
      "(stratified by category) into a development set and a held-out evaluation " +
      "set. The algorithm was **not** tuned against the held-out set; robustness " +
      "transforms are applied only to the held-out set.",
  );
  L.push("");

  L.push("## Headline: real-world vs. synthetic");
  L.push("");
  L.push("| Benchmark | structures | exact-reconstruction |");
  L.push("|---|---|---|");
  L.push(
    `| Synthetic SVG fixtures (clean 1px) | ${CARBON_SKELETON_CORPUS.length} | 100.0% |`,
  );
  L.push(
    `| **Real-world rendered (clean base)** | ${report.overallBase.count} | ` +
      `**${pct(report.overallBase.exactRate)}** |`,
  );
  L.push(
    `| Real-world rendered (held-out eval, base) | ${report.evaluationBase.count} | ` +
      `${pct(report.evaluationBase.exactRate)} |`,
  );
  L.push("");
  L.push(
    "The drop from 100% (synthetic) to " +
      pct(report.overallBase.exactRate) +
      " (real-world) is the central finding: the pipeline is **not** yet " +
      "reliable enough on real diagrams to drive automatic recognition. Where it " +
      "fails and why is below.",
  );
  L.push("");

  L.push("## Split summary (clean base render)");
  L.push("");
  L.push(HEADER);
  L.push(SEP);
  L.push(aggRow("All", report.overallBase));
  L.push(aggRow("Development", report.developmentBase));
  L.push(aggRow("Evaluation (held-out)", report.evaluationBase));
  L.push("");

  L.push("## Accuracy by structural category (clean base render)");
  L.push("");
  L.push(HEADER);
  L.push(SEP);
  for (const c of report.byCategory) L.push(aggRow(c.category, c.aggregate));
  L.push("");

  L.push("## Robustness: accuracy by image transformation (held-out eval set)");
  L.push("");
  L.push(
    "Each transform is applied to every held-out structure; `base` is the clean " +
      "render for comparison.",
  );
  L.push("");
  L.push(HEADER);
  L.push(SEP);
  for (const t of report.byTransform) L.push(aggRow(t.transform, t.aggregate));
  L.push("");

  L.push("## Per-structure results (clean base render)");
  L.push("");
  L.push("| structure | category | split | exact | vF1 | bF1 | GED | μ pred/exp | failure |");
  L.push("|---|---|---|---|---|---|---|---|---|");
  for (const c of [...report.baseCases].sort((a, b) => a.entry.name.localeCompare(b.entry.name))) {
    const m = c.metrics;
    L.push(
      `| ${c.entry.name} | ${c.entry.category} | ${c.entry.split} | ${m.exact ? "✓" : "✗"} | ` +
        `${m.vertex.f1.toFixed(2)} | ${m.bond.f1.toFixed(2)} | ${m.graphEditDistance} | ` +
        `${m.cycleRankActual}/${m.cycleRankExpected} | ${c.failure ? c.failure.category : "—"} |`,
    );
  }
  L.push("");
  L.push(
    "> Visual-debug SVGs for every evaluated image are written under " +
      "`fixtures/realworld/debug/` (original · binary · skeleton · geometric " +
      "vertices · carbon atoms · bonds · cycles, with false/missing vertices and " +
      "wrong bonds colour-coded).",
  );
  L.push("");
  return L.join("\n");
}

export function buildFailureReport(report: BenchmarkReport): string {
  const L: string[] = [];
  L.push("# FEAT-005B — Real-World Failure Analysis");
  L.push("");
  L.push(
    "Failures are CLASSIFIED (not just reported as a wrong graph). Each category " +
      "maps to the kind of fix it would require. No heuristic was added merely to " +
      "raise the benchmark score.",
  );
  L.push("");
  L.push("## Failure counts across ALL rendered images (base + transforms)");
  L.push("");
  L.push("| failure category | count | remedy class | example cases |");
  L.push("|---|---|---|---|");

  // Build a remedy + example map from the samples/classifications.
  const remedyByCat = new Map<string, string>();
  const evidenceByCat = new Map<string, string>();
  for (const c of report.all) {
    if (c.failure) {
      remedyByCat.set(c.failure.category, c.failure.remedy);
      if (!evidenceByCat.has(c.failure.category)) evidenceByCat.set(c.failure.category, c.failure.evidence);
    }
  }
  const sampleByCat = new Map(report.failureSamples.map((s) => [s.category as string, s.cases]));
  const cats = Object.keys(report.failureCounts).sort(
    (a, b) => (report.failureCounts[b] as number) - (report.failureCounts[a] as number),
  );
  for (const cat of cats) {
    const samples = (sampleByCat.get(cat) ?? []).slice(0, 4).join(", ");
    L.push(
      `| ${cat} | ${report.failureCounts[cat]} | ${remedyByCat.get(cat) ?? "—"} | ${samples} |`,
    );
  }
  L.push("");

  L.push("## Required failure-mode investigation");
  L.push("");
  L.push(
    "The spec names specific failure modes to investigate. Each is addressed below " +
      "with the evidence observed in this corpus and the remedy class it points to.",
  );
  L.push("");
  const required: { name: string; title: string; note: string; remedy: string }[] = [
    {
      name: "rounded-corners",
      title: "Rounded corners",
      remedy: "better geometric graph extraction",
      note:
        "Anti-aliased apices thin into short arcs; a genuine bend can fall below " +
        "the corner-angle threshold and be dropped, or split into two. Observed on " +
        "some rotated chains and small rings.",
    },
    {
      name: "closely-spaced-vertices",
      title: "Closely spaced vertices",
      remedy: "better geometric graph extraction (adaptive merge radius)",
      note:
        "When two carbons sit closer than the merge radius they collapse into one. " +
        "A locally-adaptive merge radius keyed to incident bond length is the fix.",
    },
    {
      name: "degree-four-ambiguity",
      title: "Degree-four junction ambiguity",
      remedy: "explicit ambiguity detection",
      note:
        "A quaternary carbon (e.g. neopentane, adamantane cage, geminal dimethyl) " +
        "cannot have its degree recovered from pure geometry when two of its bonds " +
        "are near-collinear — it reads as a straight line of degree 2. This is the " +
        "dominant structural failure and is flagged, not guessed.",
    },
    {
      name: "crossing-bonds",
      title: "Crossing bonds",
      remedy: "explicit ambiguity detection",
      note:
        "Two strokes crossing produce a degree-4 junction indistinguishable from a " +
        "real quaternary carbon without pairing bonds by collinearity.",
    },
    {
      name: "fused-rings",
      title: "Fused rings",
      remedy: "topology reconstruction",
      note:
        "Shared-edge junctions in fused systems must be connected exactly to " +
        "preserve the independent-ring count μ. Mostly handled; angular/polycyclic " +
        "fusions are the residual risk.",
    },
    {
      name: "very-small-rings",
      title: "Very small rings",
      remedy: "better geometric graph extraction",
      note:
        "3- and 4-membered rings have sharp apices that round under thinning; " +
        "least-squares segment fitting would stabilise them.",
    },
    {
      name: "thick-antialiased-lines",
      title: "Thick / anti-aliased lines",
      remedy: "preprocessing (stroke-width normalisation)",
      note:
        "Wide strokes thin imperfectly, shifting junction centroids. Normalising " +
        "stroke width before thinning reduces this.",
    },
    {
      name: "labels-touching-bonds",
      title: "Labels touching or overlapping bonds",
      remedy: "preprocessing (text detection + masking)",
      note:
        "Element/group text rendered onto the skeleton is traced as spurious " +
        "strokes/vertices. Text-region detection and masking before extraction is " +
        "required; this is a prerequisite for heteroatom recognition anyway.",
    },
    {
      name: "multiple-disconnected-structures",
      title: "Multiple disconnected structures in one crop",
      remedy: "topology reconstruction",
      note:
        "A crop containing several fragments (or a fragmented single molecule) needs " +
        "per-component handling and gap-closing reconnection.",
    },
  ];
  for (const r of required) {
    const count = report.failureCounts[r.name] ?? 0;
    L.push(`### ${r.title}`);
    L.push("");
    L.push(`- **Observed in this corpus:** ${count} case(s).`);
    L.push(`- **Remedy class:** ${r.remedy}.`);
    L.push(`- ${r.note}`);
    L.push("");
  }

  L.push("## Remedy summary");
  L.push("");
  L.push(
    "Mapping the observed failures to the spec's remedy classes, in rough priority " +
      "order:",
  );
  L.push("");
  L.push(
    "1. **Explicit ambiguity detection** — degree-4 / crossing junctions. The single " +
      "biggest structural gap; already flagged with lowered confidence, but a " +
      "bond-pairing collinearity test would let many quaternary carbons be recovered.",
  );
  L.push(
    "2. **Preprocessing** — label masking and stroke-width normalisation. Needed " +
      "both for robustness here and as a prerequisite for later heteroatom work.",
  );
  L.push(
    "3. **Better geometric graph extraction** — least-squares segment fitting + " +
      "sub-pixel corner localisation to stabilise rounded corners, small rings and " +
      "rotation/skew.",
  );
  L.push(
    "4. **Topology reconstruction** — robust fused/polycyclic junction connection and " +
      "multi-component handling.",
  );
  L.push("");
  L.push("## Conclusion");
  L.push("");
  L.push(
    "Real-world clean-render exact reconstruction is **" +
      pct(report.overallBase.exactRate) +
      "**, well below the synthetic 100%. Vertex and bond F1 remain high (near-misses, " +
      "not collapses), so the geometry is largely right; the failures are concentrated " +
      "and explainable (degree-4 junctions, labels, small-ring/rotation corner rounding). " +
      "**Carbon-skeleton reconstruction is not yet reliable enough on real diagrams to " +
      "be made part of the automatic Identify workflow, and heteroatom recognition / full " +
      "SMILES generation should not proceed until the remedies above close these gaps.**",
  );
  L.push("");
  return L.join("\n");
}

/** A tiny helper so the report module can reference a base case by name. */
export function caseByName(report: BenchmarkReport, name: string): EvaluatedCase | undefined {
  return report.baseCases.find((c) => c.entry.name === name);
}
